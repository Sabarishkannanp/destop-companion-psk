using System.Net;
using System.Net.Http.Headers;
using System.Text.Json;
using SixLabors.ImageSharp;
using SixLabors.ImageSharp.PixelFormats;
using SixLabors.ImageSharp.Processing;

var root = Directory.GetCurrentDirectory();
while (!File.Exists(Path.Combine(root, ".env.example")))
    root = Directory.GetParent(root)?.FullName ?? throw new InvalidOperationException("Run from the Buddy repository.");
var output = Path.Combine(root, "src", "Buddy", "Assets", "Avatar");
Directory.CreateDirectory(output);
var assets = Directory.GetParent(output)!.FullName;
var force = args.Contains("--force");
var names = new[] { "idle_front", "walk_right_1", "walk_right_2", "walk_right_3", "walk_right_4", "drink_water", "wave", "sad" };
var poses = new[] { "standing relaxed, facing camera, smiling", "walking right, side view, left leg forward", "walking right, legs passing (mid-stride)", "walking right, right leg forward", "walking right, legs passing, slight bounce", "facing camera, holding a clear water bottle up, happy", "facing camera, waving with right hand", "facing camera, slightly disappointed, shoulders down" };
const string basePrompt = "Turn this person into a full-body 3D Pixar/Disney-style cartoon character. Keep the same face, skin tone, hairstyle, beard and glasses (if any). Casual outfit: denim shirt, dark jeans, white sneakers. Full body visible head to toe, centered, feet touching the bottom edge, consistent scale, soft studio lighting, transparent background, no text, no ground shadow. ";
try
{
    var sheetIndex=Array.IndexOf(args,"--import-walk-sheet");
    if(sheetIndex>=0)
    {
        if(sheetIndex+1>=args.Length)throw new ArgumentException("Provide the walk sheet path after --import-walk-sheet.");
        using var sheet=Image.Load<Rgba32>(args[sheetIndex+1]);
        var w=sheet.Width/4;var h=sheet.Height/2;
        var frames=new List<Image<Rgba32>>();
        try
        {
            // Crop all cells using shared bounds, so the body does not change scale per frame.
            int left=w,top=h,right=-1,bottom=-1;
            for(var i=0;i<8;i++)
            {
                var tile=sheet.Clone(c=>c.Crop(new Rectangle((i%4)*w,(i/4)*h,w,h)));frames.Add(tile);
                for(var y=0;y<h;y++)for(var x=0;x<w;x++)if(tile[x,y].A>64)
                {left=Math.Min(left,x);top=Math.Min(top,y);right=Math.Max(right,x);bottom=Math.Max(bottom,y);}
            }
            if(right<left)throw new InvalidDataException("Walk sheet has no visible pixels.");
            var bounds=new Rectangle(left,top,right-left+1,bottom-top+1);
            var scale=Math.Min(400d/bounds.Width,600d/bounds.Height);
            var newW=Math.Max(1,(int)Math.Round(bounds.Width*scale));var newH=Math.Max(1,(int)Math.Round(bounds.Height*scale));
            for(var i=0;i<8;i++)
            {
                var foot=top;
                for(var y=top;y<=bottom;y++)for(var x=left;x<=right;x++)if(frames[i][x,y].A>64)foot=Math.Max(foot,y);
                var height=foot-top+1;var scaledH=Math.Max(1,(int)Math.Round(height*scale));
                frames[i].Mutate(c=>c.Crop(new Rectangle(left,top,bounds.Width,height)).Resize(newW,scaledH));
                using var canvas=new Image<Rgba32>(400,600);canvas.Mutate(c=>c.DrawImage(frames[i],new Point((400-newW)/2,600-scaledH),1));
                canvas.SaveAsPng(Path.Combine(output,$"walk_right_{i+1}.png"));
            }
        }
        finally {foreach(var frame in frames)frame.Dispose();}
        Console.WriteLine("Imported eight frames at one shared scale and baseline.");return;
    }
    // Also supports preparing assets generated by the built-in image tool without API access.
    if (args.Contains("--normalize"))
    {
        foreach (var name in names) { var p = Path.Combine(output, name + ".png"); if (File.Exists(p)) Normalize(p); }
        MakeIcons();
        Console.WriteLine("Normalized sprites and wrote app.ico / tray.png.");
        return;
    }
    if (!force && names.All(n => File.Exists(Path.Combine(output, n + ".png")))) { MakeIcons(); Console.WriteLine("All poses exist; skipped. Use --force to regenerate."); return; }
    var key = Environment.GetEnvironmentVariable("OPENAI_API_KEY");
    var env = Path.Combine(root, ".env");
    if (string.IsNullOrWhiteSpace(key) && File.Exists(env))
        key = File.ReadLines(env).Select(l => l.Trim()).Where(l => l.StartsWith("OPENAI_API_KEY=", StringComparison.Ordinal)).Select(l => l[(l.IndexOf('=') + 1)..].Trim().Trim('\"', '\'')).FirstOrDefault();
    if (string.IsNullOrWhiteSpace(key)) throw new InvalidOperationException("Set OPENAI_API_KEY locally or in .env. Do not paste your key into chat.");
    var photo = Path.Combine(root, "assets", "source", "me.jpg");
    if (!File.Exists(photo)) throw new FileNotFoundException("Save your reference photo to assets/source/me.jpg.", photo);
    byte[] photoPng;
    using (var source = Image.Load<Rgba32>(photo)) { using var ms = new MemoryStream(); source.SaveAsPng(ms); photoPng = ms.ToArray(); }
    using var client = new HttpClient { Timeout = TimeSpan.FromMinutes(8) };
    client.DefaultRequestHeaders.Authorization = new AuthenticationHeaderValue("Bearer", key);
    for (var i = 0; i < names.Length; i++)
    {
        var target = Path.Combine(output, names[i] + ".png");
        if (File.Exists(target) && !force) { Console.WriteLine($"[{i+1}/8] {names[i]}: skipped"); continue; }
        Console.WriteLine($"[{i+1}/8] Generating {names[i]}...");
        for (var attempt = 0; ; attempt++)
        {
            try
            {
                using var form = new MultipartFormDataContent();
                foreach (var pair in new Dictionary<string, string> { ["model"] = "gpt-image-1", ["size"] = "1024x1536", ["background"] = "transparent", ["output_format"] = "png", ["quality"] = "high", ["prompt"] = basePrompt + "Pose: " + poses[i] }) form.Add(new StringContent(pair.Value), pair.Key);
                AddImage(form, photoPng, "me.png");
                if (i > 0) AddImage(form, File.ReadAllBytes(Path.Combine(output, "idle_front.png")), "idle_front.png");
                using var response = await client.PostAsync("https://api.openai.com/v1/images/edits", form);
                if (!response.IsSuccessStatusCode)
                {
                    // Do not echo response bodies, which can include account or request details.
                    if ((int)response.StatusCode is 429 or >= 500) throw new HttpRequestException($"Image API returned {(int)response.StatusCode}.", null, response.StatusCode);
                    throw new InvalidOperationException($"Image API returned {(int)response.StatusCode}. Check account access, billing, and model permissions.");
                }
                using var json = JsonDocument.Parse(await response.Content.ReadAsStringAsync());
                var bytes = Convert.FromBase64String(json.RootElement.GetProperty("data")[0].GetProperty("b64_json").GetString()!);
                var temp = target + ".tmp";
                await File.WriteAllBytesAsync(temp, bytes); Normalize(temp); File.Move(temp, target, true);
                Console.WriteLine($"Saved {names[i]}.png"); break;
            }
            catch (Exception ex) when (attempt < 2 && ex is HttpRequestException or TaskCanceledException)
            { Console.WriteLine($"Retry {attempt+1}/2 in {3 * (attempt+1)}s..."); await Task.Delay(TimeSpan.FromSeconds(3 * (attempt+1))); }
        }
    }
    MakeIcons();
}
catch (Exception ex) { Console.Error.WriteLine(ex.Message); Environment.ExitCode = 1; }

void AddImage(MultipartFormDataContent form, byte[] bytes, string name)
{ var content = new ByteArrayContent(bytes); content.Headers.ContentType = new MediaTypeHeaderValue("image/png"); form.Add(content, "image[]", name); }
void Normalize(string path)
{
    using var image = Image.Load<Rgba32>(path);
    int left = image.Width, top = image.Height, right = -1, bottom = -1;
    for (var y = 0; y < image.Height; y++) for (var x = 0; x < image.Width; x++)
        if (image[x,y].A > 8) { left = Math.Min(left,x); top = Math.Min(top,y); right = Math.Max(right,x); bottom = Math.Max(bottom,y); }
    if (right < left) throw new InvalidDataException("Generated image was empty.");
    image.Mutate(c => c.Crop(new Rectangle(left, top, right-left+1, bottom-top+1)));
    var ratio = Math.Min(400d / image.Width, 600d / image.Height);
    image.Mutate(c => c.Resize(Math.Max(1,(int)Math.Round(image.Width*ratio)), Math.Max(1,(int)Math.Round(image.Height*ratio))));
    using var canvas = new Image<Rgba32>(400,600);
    canvas.Mutate(c => c.DrawImage(image,new Point((400-image.Width)/2,600-image.Height),1)); canvas.SaveAsPng(path);
}
void MakeIcons()
{
    var idle = Path.Combine(output,"idle_front.png"); if (!File.Exists(idle)) return;
    using var source = Image.Load<Rgba32>(idle);
    using var face = source.Clone(c => c.Crop(new Rectangle(80,0,240,240)));
    using (var tray = face.Clone(c => c.Resize(32,32))) tray.SaveAsPng(Path.Combine(assets,"tray.png"));
    var sizes = new[] {16,32,48,256}; var frames = sizes.Select(s => { using var f = face.Clone(c=>c.Resize(s,s)); using var ms = new MemoryStream(); f.SaveAsPng(ms); return ms.ToArray(); }).ToArray();
    using var writer = new BinaryWriter(File.Create(Path.Combine(assets,"app.ico")));
    writer.Write((ushort)0); writer.Write((ushort)1); writer.Write((ushort)sizes.Length);
    var offset = 6 + 16*sizes.Length;
    for (var i=0;i<sizes.Length;i++) { writer.Write((byte)(sizes[i]==256?0:sizes[i])); writer.Write((byte)(sizes[i]==256?0:sizes[i])); writer.Write((byte)0); writer.Write((byte)0); writer.Write((ushort)1); writer.Write((ushort)32); writer.Write(frames[i].Length); writer.Write(offset); offset += frames[i].Length; }
    foreach (var frame in frames) writer.Write(frame);
}
